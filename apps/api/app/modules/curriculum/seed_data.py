from typing import Dict, Any, List, Optional
from pydantic import BaseModel


class ExerciseConcept(BaseModel):
    summary: str
    syntax: Optional[str] = None
    key_points: Optional[List[str]] = None
    execution_order_note: Optional[str] = None


class SampleTableData(BaseModel):
    tableName: str
    columns: List[str]
    rows: List[List[Any]]


class ExercisePublicDTO(BaseModel):
    id: str
    module_id: str
    title: str
    prompt: str
    initial_code: str
    xp_reward: int
    difficulty: str
    check_order: bool
    sort_order: int
    operational_status: str = "active"
    execution_mode: str = "read_only"
    hints: List[str] = []
    concept: Optional[ExerciseConcept] = None
    objectives: Optional[List[str]] = None
    sample_tables: Optional[List[SampleTableData]] = None


class ExerciseDetail(BaseModel):
    id: str
    module_id: str
    title: str
    prompt: str
    initial_code: str
    solution_query: str
    xp_reward: int
    difficulty: str
    check_order: bool
    sort_order: int
    operational_status: str = "active"
    execution_mode: str = "read_only"
    verification_query: Optional[str] = None
    setup_sql: Optional[str] = None
    hints: List[str] = []
    concept: Optional[ExerciseConcept] = None
    objectives: Optional[List[str]] = None
    sample_tables: Optional[List[SampleTableData]] = None

    def to_public_dto(self) -> ExercisePublicDTO:
        return ExercisePublicDTO(
            id=self.id,
            module_id=self.module_id,
            title=self.title,
            prompt=self.prompt,
            initial_code=self.initial_code,
            xp_reward=self.xp_reward,
            difficulty=self.difficulty,
            check_order=self.check_order,
            sort_order=self.sort_order,
            operational_status=self.operational_status,
            execution_mode=self.execution_mode,
            hints=self.hints,
            concept=self.concept,
            objectives=self.objectives,
            sample_tables=self.sample_tables,
        )


